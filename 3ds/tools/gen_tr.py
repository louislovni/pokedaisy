#!/usr/bin/env python3
"""Writes 3ds/core/pd_tr_fr_gen.c: the companion's French (pd_tr).

Two sources, the second winning:
  - the app's translation tables (app/.../companion/i18n/*.kt and guide/*.kt): every `"ENGLISH" to Tr(..., fr = "...")`;
    `{0}`-style placeholders in the English become a format (`%s`), the French keeps them;
  - 3ds/core/i18n/fr.tsv: the C companion's own strings (English <TAB> French, one per line, `#` comments). An English
    with printf conversions (%d, %s, %ld ...) is a format; its French takes `{0}`, `{1}` .. for them, in order.

    python3 3ds/tools/gen_tr.py
"""
import glob
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
I18N = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/i18n")
TSV = os.path.join(ROOT, "3ds/core/i18n/fr.tsv")
OUT = os.path.join(ROOT, "3ds/core/pd_tr_fr_gen.c")

STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
CONVERSION = re.compile(r"%[-+ 0-9.]*[lhz]*[diuxXsc]")


def unkotlin(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            c = s[i + 1]
            out.append({"n": "\n", "t": "\t", '"': '"', "\\": "\\", "$": "$", "'": "'"}.get(c, c))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def kotlin_tables():
    pairs = {}
    files = glob.glob(os.path.join(I18N, "*.kt")) + glob.glob(os.path.join(I18N, "guide", "*.kt"))
    for path in sorted(files):
        text = open(path, encoding="utf-8").read()
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"\s+to\s+Tr\(', text):
            # The Tr(...) call, its strings skipped while looking for the closing parenthesis.
            i, depth = m.end(), 1
            while i < len(text) and depth:
                if text[i] == '"':
                    j = STRING.match(text, i)
                    i = j.end() if j else i + 1
                    continue
                depth += {"(": 1, ")": -1}.get(text[i], 0)
                i += 1
            fr = re.search(r'\bfr\s*=\s*"((?:[^"\\]|\\.)*)"', text[m.end():i])
            if not fr:
                continue
            en, tr = unkotlin(m.group(1)), unkotlin(fr.group(1))
            if "${" in en or "${" in tr or not en.strip():
                continue
            pairs[en] = tr
    return pairs


def tsv():
    pairs = {}
    if not os.path.exists(TSV):
        return pairs
    for n, line in enumerate(open(TSV, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        assert len(parts) == 2, f"fr.tsv:{n}: expected ENGLISH<TAB>FRENCH"
        en, tr = (p.replace("\\n", "\n").replace("\\t", "\t") for p in parts)
        pairs[en] = tr
    return pairs


def c_string(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    # A hex escape swallows the hex digits after it: there are none (UTF-8 is written as is).
    return '"' + "".join(out) + '"'


def main():
    exact, formats = {}, {}
    for en, tr in list(kotlin_tables().items()) + list(tsv().items()):
        if re.search(r"\{\d\}", en):
            # The app's placeholders: any text (a number prints as text too).
            fmt = re.sub(r"\{\d\}", "%s", en.replace("%", "%%"))
            formats[fmt] = tr
            exact.pop(en, None)
        elif CONVERSION.search(en):
            formats[en] = tr
        else:
            exact[en] = tr
    # Exact by strcmp order (bytes); formats longest first (the most specific wins).
    keys = sorted(exact, key=lambda k: k.encode("utf-8"))
    fkeys = sorted(formats, key=lambda k: (-len(k), k))
    out = [
        "// Generated by 3ds/tools/gen_tr.py from the app's translation tables and 3ds/core/i18n/fr.tsv - do not hand-edit.",
        '#include "pd_tr.h"',
        "",
        f"const struct pd_tr_entry pd_tr_fr[{len(keys)}] = {{",
    ]
    out += [f"    {{ {c_string(k)}, {c_string(exact[k])} }}," for k in keys]
    out += ["};", f"const int pd_tr_fr_count = {len(keys)};", "",
            f"const struct pd_tr_entry pd_tr_fr_formats[{len(fkeys)}] = {{"]
    out += [f"    {{ {c_string(k)}, {c_string(formats[k])} }}," for k in fkeys]
    out += ["};", f"const int pd_tr_fr_format_count = {len(fkeys)};", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(keys)} strings, {len(fkeys)} formats")


if __name__ == "__main__":
    main()
