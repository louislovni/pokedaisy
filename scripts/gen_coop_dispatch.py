#!/usr/bin/env python3
"""The co-op bridge for two carts in one app (English and French Emerald): pk_coop*.c is built twice, each build's
external names renamed (pk_coop_x -> pk_coopen_x / pk_coopfr_x, by a header pre-included with -include), and
pk_coop_dispatch.c puts the pk_coop_x the rest of the app calls back, each one handing over to the loaded cart's build.

Writes app/src/main/cpp/pk_coop_en_names.h, pk_coop_fr_names.h (the names) and pk_coop_dispatch.c (the calls). The list of
names is the one already in pk_coop_fr_names.h: add a line there when pk_coop*.c gains an external name (nm the objects
for their T / D / B / R symbols), then run this. The functions dispatched are those declared in pk_coop.h, pk_coop_after.h,
pk_coop_field.h and pk_coop_lock.h; the rest are the bridge's own between its files."""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPP = os.path.join(ROOT, "app/src/main/cpp")
HEADERS = ["pk_coop.h", "pk_coop_after.h", "pk_coop_field.h", "pk_coop_lock.h"]
# No cart is known yet, or each build keeps its own state: both builds are told.
BOTH = {"pk_coop_reset", "pk_coop_lock_reset", "pk_coop_uninstall", "pk_coop_lock_uninstall", "pk_coop_after_set_call",
        "pk_coop_after_set_cap"}


def names():
    text = open(os.path.join(CPP, "pk_coop_fr_names.h")).read()
    return sorted(set(re.findall(r"#define (pk_coop_\w+) pk_coopfr_\w+", text)))


def prototypes():
    src = ""
    for h in HEADERS:
        t = open(os.path.join(CPP, h)).read()
        t = re.sub(r"//[^\n]*", "", t)
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
        src += t + "\n"
    found = {}
    for m in re.finditer(r"(?:^|\n|;)\s*((?:const\s+)?(?:struct\s+)?\w+[\s\*]+)(pk_coop_\w+)\s*\(([^)]*)\)\s*;", src):
        ret, name, args = m.group(1).strip(), m.group(2), " ".join(m.group(3).split())
        found[name] = (ret, args)
    return found


def arg_names(args):
    if args in ("", "void"):
        return []
    out = []
    for a in args.split(","):
        m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", a.strip())
        out.append(m.group(1))
    return out


def header(kind, all_names):
    guard = "PK_COOP_%s_NAMES_H" % kind.upper()
    lines = ["/* Generated by scripts/gen_coop_dispatch.py: every external name of pk_coop*.c renamed for the %s cart's build" % (
        "English" if kind == "en" else "French"), " * (pk_coop_x -> pk_coop%s_x); pre-included with -include. */" % kind,
        "#ifndef " + guard, "#define " + guard]
    lines += ["#define %s pk_coop%s_%s" % (n, kind, n[len("pk_coop_"):]) for n in all_names]
    return "\n".join(lines + ["#endif", ""])


def main():
    all_names = names()
    protos = prototypes()
    for kind in ("en", "fr"):
        open(os.path.join(CPP, "pk_coop_%s_names.h" % kind), "w").write(header(kind, all_names))
    out = ["/* Generated by scripts/gen_coop_dispatch.py: the co-op bridge's calls, each handed to the build of the loaded cart",
           " * (English or French Emerald: its game code's last letter, ROM 0x080000AF). GPL-3.0, see NOTICE. */",
           '#include "pk_coop.h"', '#include "pk_coop_after.h"', '#include "pk_coop_field.h"', '#include "pk_coop_lock.h"',
           "#include <mgba/core/core.h>", "", "static int coopFrench; /* the last cart seen: the calls with no core go to it */", "",
           "int pk_coop_french(struct mCore* core) {",
           "    if (core)",
           "        coopFrench = core->busRead8(core, 0x080000AF) == 'F' && core->busRead8(core, 0x080000AC) == 'B';",
           "    return coopFrench;", "}", ""]
    for n in all_names:
        if n not in protos:
            continue
        ret, args = protos[n]
        an = arg_names(args)
        tail = n[len("pk_coop_"):]
        call = "(%s)" % ", ".join(an)
        has_core = bool(re.match(r"struct mCore\s*\*\s*core", args))
        ret_kw = "" if ret == "void" else "return "
        out.append("%s pk_coopen_%s(%s);" % (ret, tail, args or "void"))
        out.append("%s pk_coopfr_%s(%s);" % (ret, tail, args or "void"))
        out.append("%s %s(%s) {" % (ret, n, args or "void"))
        if n in BOTH:
            assert ret == "void", n
            out.append("    pk_coopen_%s%s;" % (tail, call))
            out.append("    pk_coopfr_%s%s;" % (tail, call))
        else:
            pick = "pk_coop_french(core)" if has_core else "coopFrench"
            out.append("    %s%s ? pk_coopfr_%s%s : pk_coopen_%s%s;" % (ret_kw, pick, tail, call, tail, call))
        out.append("}")
        out.append("")
    open(os.path.join(CPP, "pk_coop_dispatch.c"), "w").write("\n".join(out))
    print("%d names, %d dispatched" % (len(all_names), sum(1 for n in all_names if n in protos)))


if __name__ == "__main__":
    main()
