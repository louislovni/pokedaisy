#!/usr/bin/env python3
"""The story spots for the libretro core's joined story battles (libretro/pd_coop_battle.inc): from the app's
CoopStoryGen.kt (scripts/gen_coop_story.py's table), the events a player can stand at to be offered one (CoopStorySpots: a
COORD trigger's tile, or beside an OBJECT; one story trainer only). Writes libretro/pd_coop_story_spots.h. Rerun after
gen_coop_story.py."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/coop/CoopStoryGen.kt")
OUT = os.path.join(ROOT, "libretro/pd_coop_story_spots.h")

text = open(SRC).read()
rows = []
for m in re.finditer(r"StoryEvent\((\d+), StoryKind\.(\w+), (-?\d+), (-?\d+), (-?\d+), (-?\d+), 0x[0-9A-F]+L, \"(\w+)\", listOf\(([^)]*)\)\)", text):
    eid, kind, group, num, x, y, label, trainers = m.groups()
    ids = [int(t) for t in trainers.split(",") if t.strip()]
    if kind in ("COORD", "OBJECT") and len(ids) == 1:
        rows.append((int(eid), 1 if kind == "OBJECT" else 0, int(group), int(num), int(x), int(y), ids[0], label))
consts = dict(re.findall(r"const val (COOP_TRAINER_FLAGS_START|COOP_SB1_FLAGS_OFF|COOP_TRAINERS_COUNT)(?:: Int)? = (0x[0-9A-Fa-f]+|\d+)", text))
lines = ["/* Generated by scripts/gen_coop_story_spots.py from CoopStoryGen.kt: the story spots a joined story battle is offered at. */",
         "#ifndef PD_COOP_STORY_SPOTS_H", "#define PD_COOP_STORY_SPOTS_H",
         "#define CB_TRAINER_FLAGS_START %s" % consts["COOP_TRAINER_FLAGS_START"],
         "#define CB_SB1_FLAGS_OFF %s" % consts["COOP_SB1_FLAGS_OFF"],
         "struct cb_story_spot { uint16_t id; uint8_t object, group, num; int8_t x, y; uint16_t trainer; };",
         "static const struct cb_story_spot CB_STORY_SPOTS[] = {"]
lines += ["    {%d, %d, %d, %d, %d, %d, %d}, /* %s */" % r for r in rows]
lines += ["};", "#endif", ""]
open(OUT, "w").write("\n".join(lines))
print(len(rows), "spots")
